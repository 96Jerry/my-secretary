// Appendix A-1 전문. 임의 수정·요약 금지. raw_goal 자리만 변수 치환.
export function buildRewriteGoalPrompt(rawGoal: string): string {
  return `## Objective
사용자가 입력한 원본 목표 텍스트를 메인 프롬프트가 활용할 수 있도록 측정 가능한 목표 명세로 재작성한다.

## Input
<raw_goal>
${rawGoal}
</raw_goal>

## Task
1. 각 목표를 별도 항목으로 분리한다.
2. 모호한 표현을 측정 가능한 기준으로 변환한다.
   예: "자랑할 수 있는 백엔드 시니어" → "시스템 설계, 멘토링, 트레이드오프 결정으로 검증되는 시니어 역량"
3. 각 목표에 다음 3가지를 부여한다:
   - 측정 지표 (정량 또는 검증 가능한 정성)
   - 추정 소요 기간 (현재 0% 가정 시)
   - 진척도 산정 기준 (몇 %를 어떻게 판단할지)
4. 사용자가 명시하지 않은 목표는 추가하지 않는다.

## Output Format
사족 없이 아래 형식으로만 출력. 마크다운 코드 블록 사용 금지.

목표 1: [재작성된 목표 명세]
- 측정 지표: [구체 metric]
- 추정 소요 기간: [기간]
- 진척도 산정 기준: [기준 설명]

목표 2: [재작성된 목표 명세]
- 측정 지표: [구체 metric]
- 추정 소요 기간: [기간]
- 진척도 산정 기준: [기준 설명]

(사용자가 입력한 목표 개수만큼 반복)

## Constraints
- 사용자가 입력하지 않은 목표를 임의로 만들지 않는다.
- 의도를 보존하되 구체성과 측정 가능성만 강화한다.
- 한국어로만 출력한다.
`;
}
